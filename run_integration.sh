#!/usr/bin/env bash
set -euo pipefail

# run_integration.sh
# Usage: ./run_integration.sh
# Ensure you run this from the repository root.

# Configurable defaults (change if needed)
COIN_LIST="config/coin_list_integration.txt"
SOCIAL_DIR="data"
PRICE_DIR="data_price"
JOINED_DIR="data_joined"
REPORTS_DIR="reports"
LOGS_DIR="logs"
BARS=500
CONCURRENCY=4
EXCHANGES="kraken,coinbasepro,binance"

BACKFILL_INVENTORY="$REPORTS_DIR/backfill_inventory_integration.csv"
JOIN_INVENTORY="$REPORTS_DIR/join_inventory_integration.csv"
BACKTEST_OUT="$REPORTS_DIR/backtest_integration.csv"
PER_SIGNAL_OUT="$REPORTS_DIR/backtest_per_coin_integration.csv"
TECH_SUMMARY_OUT="$REPORTS_DIR/backtest_tech_summary_integration.csv"
ELIG_DIAG="$REPORTS_DIR/eligibility_diagnostics_integration.csv.gz"
BACKFILL_LOG="$LOGS_DIR/backfill_integration.log"

mkdir -p config "$PRICE_DIR" "$JOINED_DIR" "$REPORTS_DIR" "$LOGS_DIR"

echo "=== STEP 1: Build top-20 coin list from LunarCrush social history (data/) ==="
python - <<'PY'
import pandas as pd, pathlib
data_dir = pathlib.Path("data")
files = list(data_dir.glob("history_*.csv"))
rows = []
for f in files:
    try:
        df = pd.read_csv(f)
        if "market_cap" in df.columns and not df["market_cap"].isna().all():
            last = pd.to_numeric(df["market_cap"], errors="coerce").dropna()
            if not last.empty:
                rows.append((f.stem.replace("history_",""), float(last.iloc[-1])))
    except Exception:
        continue
rows = sorted(rows, key=lambda x: x[1], reverse=True)
top20 = [r[0] for r in rows[:20]]
out = pathlib.Path("config")
out.mkdir(parents=True, exist_ok=True)
with (out/"coin_list_integration.txt").open("w") as f:
    f.write("\n".join(top20))
print("Wrote", len(top20), "coins to config/coin_list_integration.txt")
print(top20)
PY

echo
echo "=== STEP 2: Run CCXT backfill (500 bars, concurrency=${CONCURRENCY}) ==="
echo "Backfill inventory -> ${BACKFILL_INVENTORY}"
python tools/ccxt_backfill.py \
  --coins-file "$COIN_LIST" \
  --bars "$BARS" \
  --out-dir "$PRICE_DIR" \
  --concurrency "$CONCURRENCY" \
  --exchanges "$EXCHANGES" \
  --inventory "$BACKFILL_INVENTORY" \
  --log "$BACKFILL_LOG"

echo
echo "Backfill complete. Inventory head:"
if [ -f "$BACKFILL_INVENTORY" ]; then
  head -n 40 "$BACKFILL_INVENTORY" | sed -n '1,40p'
else
  echo "No backfill inventory file found: $BACKFILL_INVENTORY"
fi

echo
echo "=== STEP 3: Join price to LunarCrush social history (data_joined/) ==="
# Create the join script on-the-fly (safe to overwrite)
cat > tools/price_join.py <<'PY'
# tools/price_join.py (auto-generated by run_integration.sh)
import argparse
from pathlib import Path
import pandas as pd

def join_one(coin_id, social_dir, price_dir, out_dir):
    social_fp = Path(social_dir) / f"history_{coin_id}.csv"
    price_fp = Path(price_dir) / f"{coin_id}.csv"
    if not social_fp.exists():
        return {"coin_id":coin_id, "status":"no_social"}
    if not price_fp.exists():
        return {"coin_id":coin_id, "status":"no_price"}
    s = pd.read_csv(social_fp, parse_dates=["time"])
    p = pd.read_csv(price_fp, parse_dates=["time"])
    p = p.sort_values("time").reset_index(drop=True)
    s = s.sort_values("time").reset_index(drop=True)
    merged = pd.merge_asof(s, p[["time","open","high","low","close","volume"]], left_on="time", right_on="time", direction="backward")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    merged.to_csv(out_dir / f"history_{coin_id}.csv", index=False, date_format="%Y-%m-%dT%H:%M:%SZ", float_format="%.10f")
    return {"coin_id":coin_id, "status":"ok", "rows":len(merged)}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--coins-file", default="config/coin_list_integration.txt")
    parser.add_argument("--social-dir", default="data")
    parser.add_argument("--price-dir", default="data_price")
    parser.add_argument("--out-dir", default="data_joined")
    args = parser.parse_args()
    coins = [l.strip() for l in open(args.coins_file) if l.strip() and not l.startswith("#")]
    results = []
    for c in coins:
        res = join_one(c, args.social_dir, args.price_dir, args.out_dir)
        print(res)
        results.append(res)
    import csv
    with open("reports/join_inventory_integration.csv","w",newline="") as f:
        w=csv.DictWriter(f, fieldnames=["coin_id","status","rows"])
        w.writeheader()
        for r in results:
            w.writerow({k:r.get(k,"") for k in ["coin_id","status","rows"]})
if __name__=="__main__":
    main()
PY

python tools/price_join.py \
  --coins-file "$COIN_LIST" \
  --social-dir "$SOCIAL_DIR" \
  --price-dir "$PRICE_DIR" \
  --out-dir "$JOINED_DIR"

echo
echo "Joined inventory head:"
if [ -f "reports/join_inventory_integration.csv" ]; then
  head -n 40 reports/join_inventory_integration.csv | sed -n '1,40p'
else
  echo "No join_inventory file found"
fi

echo
echo "=== STEP 4: Run the backtest over data_joined (top-20 smoke) ==="
python backtest.py \
  --data-dir "$JOINED_DIR" \
  --output "$BACKTEST_OUT" \
  --per-signal "$PER_SIGNAL_OUT" \
  --tech-summary "$TECH_SUMMARY_OUT" \
  --thresholds "20,25,30,35,40" \
  --horizons "7,14,30" \
  --strategy all \
  --matrix \
  --top 20 \
  --exclude-last-bar \
  --no-compress-output

echo
echo "Backtest finished. Matrix head:"
if [ -f "$BACKTEST_OUT" ]; then
  head -n 40 "$BACKTEST_OUT" | sed -n '1,40p'
fi

echo
echo "=== STEP 5: Run EMA eligibility diagnostics ==="
# Per-signal may be gz or not; if uncompressed but named without .gz the tool can still read
PER_SIGNAL_PATH="$PER_SIGNAL_OUT"
# If backtest wrote compressed variant, try the gz name
if [ ! -f "$PER_SIGNAL_PATH" ] && [ -f "${PER_SIGNAL_PATH}.gz" ]; then
  PER_SIGNAL_PATH="${PER_SIGNAL_PATH}.gz"
fi

python tools/diagnose_ema_eligibility.py --per-signal "$PER_SIGNAL_PATH" --out "$ELIG_DIAG"

echo
echo "Eligibility diagnostics (top lines):"
gzip -d -c "$ELIG_DIAG" | head -n 40 || true

echo
echo "=== SUMMARY ==="
echo "Backfill inventory: $BACKFILL_INVENTORY"
echo "Join inventory: reports/join_inventory_integration.csv"
echo "Backtest matrix: $BACKTEST_OUT"
echo "Per-signal: $PER_SIGNAL_PATH"
echo "Tech summary: $TECH_SUMMARY_OUT"
echo "Eligibility diagnostics: $ELIG_DIAG"
echo "Backfill log: $BACKFILL_LOG"

echo
echo "Paste the following outputs for review:"
echo "  - head $BACKFILL_INVENTORY"
echo "  - head reports/join_inventory_integration.csv"
echo "  - console summary printed at end of backtest.py (check your terminal)"
echo "  - gzip -d -c $PER_SIGNAL_PATH | head -n 20"
echo "  - gzip -d -c $ELIG_DIAG | head -n 40"
echo
echo "If you want me to run parity checks too, export TradingView EMA CSVs (time, ema50, ema100, ema200) for 5 sample symbols under tv_exports/ and tell me to run the parity checks."
